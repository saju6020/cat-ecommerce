type Sent = Awaited<ReturnType<BrowserContext['request']['post']>>;

/** A state-changing call from a signed-in browser context (cookies + CSRF, as the app sends them). */
async function send(
  context: BrowserContext,
  method: 'post' | 'put',
  path: string,
  data?: unknown,
  staffCall = false,
): Promise<Sent> {
  const headers: Record<string, string> = {
    'X-CSRF-Token': await csrf(context),
    'Idempotency-Key': randomUUID(),
  };
  if (staffCall) headers['X-Branch-Id'] = seed.branchId;
  return context.request[method](`${API}${path}`, { headers, data });
}

