/** Enquire, give the profile, reserve, pay the earmarked deposit and wait until the stay is Confirmed. */
async function reserveAndConfirm(
  ownerContext: BrowserContext,
  staffCtx: BrowserContext,
  cat: string,
  unitType: string,
  arrivalOn: string,
  departureOn: string,
  deposit: string,
): Promise<string> {
  const enquiry = await send(ownerContext, 'post', '/api/customers/me/boarding/enquiries', {
    branchId: seed.branchId,
    arrivalOn,
    departureOn,
    unitType,
    catIds: [seed.cats[cat]],
  });
  expect(enquiry.status(), await enquiry.text()).toBe(201);
  const id = ((await enquiry.json()) as { stayId: string }).stayId;
  const profile = await send(
    ownerContext,
    'put',
    `/api/customers/me/boarding/stays/${id}/cats/${seed.cats[cat]}/care-profile`,
    PROFILE,
  );
  expect(profile.status(), await profile.text()).toBe(204);
  const reserve = await send(
    ownerContext,
    'post',
    `/api/customers/me/boarding/stays/${id}/reserve`,
  );
  expect(reserve.status(), await reserve.text()).toBe(200);
  const payment = await send(
    staffCtx,
    'post',
    '/api/staff/billing/payments',
    {
      customerId: seed.customer.id,
      method: 'CashInStore',
      amount: deposit,
      receivedOn: today,
      earmark: { kind: 'BoardingStay', sourceId: id, label: 'Boarding deposit' },
      allocations: [],
    },
    true,
  );
  expect(payment.status(), await payment.text()).toBeLessThan(300);
  await expect
    .poll(
      async () => {
        const view = await staffCtx.request.get(`${API}/api/staff/boarding/stays/${id}`, {
          headers: { 'X-Branch-Id': seed.branchId },
        });
        return ((await view.json()) as { status: string }).status;
      },
      { timeout: 120_000, intervals: [5_000] },
    )
    .toBe('Confirmed');
  return id;
}

