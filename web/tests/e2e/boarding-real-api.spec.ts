/** Signs in with a fetch from the app's own origin, so the session cookies are set exactly as the app does. */
async function signIn(
  page: Page,
  path: string,
  identifier: string,
  password: string,
  home: string,
) {
  await page.goto(home);
  await page.waitForLoadState('networkidle');
  const status = await page.evaluate(
    async ({ api, path, identifier, password }) => {
      const response = await fetch(`${api}${path}`, {
        method: 'POST',
        credentials: 'include',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ identifier, password }),
      });
      return response.status;
    },
    { api: API, path, identifier, password },
  );
  expect(status).toBe(200);
}

async function csrf(context: BrowserContext): Promise<string> {
  const cookie = (await context.cookies(API)).find((c) => c.name === 'pc_csrf');
  return decodeURIComponent(cookie?.value ?? '');
}

