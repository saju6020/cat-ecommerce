    private sealed record DiscoveredEndpoint(string Action, string OwnerScope, string Method, string RouteTemplate)
    {
        public string Key => $"{Method} {RouteTemplate}";
    }

    private static List<DiscoveredEndpoint> DiscoverEndpoints()
    {
        var results = new List<DiscoveredEndpoint>();

        foreach (var controllerType in new[] { typeof(CatsController), typeof(VaccinesController) })
        {
            var controllerRoute = controllerType.GetCustomAttribute<RouteAttribute>()!.Template!;

            foreach (var method in controllerType.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
            {
                var httpAttribute = method.GetCustomAttributes().OfType<HttpMethodAttribute>().FirstOrDefault();
                if (httpAttribute is null) continue;

                var requireAction = method.GetCustomAttribute<RequireActionAttribute>();
                if (requireAction is null) continue; // U-A1 already guards "every action has exactly one marker" elsewhere.

                var action = (string)requireAction.Arguments![0]!;
                var ownerScope = requireAction.Arguments![1]!.ToString()!;
                var httpMethod = httpAttribute.HttpMethods.First();
                var routeSuffix = httpAttribute.Template;
                var routeTemplate = string.IsNullOrEmpty(routeSuffix) ? controllerRoute : $"{controllerRoute}/{routeSuffix}";

                results.Add(new DiscoveredEndpoint(action, ownerScope, httpMethod, routeTemplate));
            }
        }

        return results;
    }

    [Fact]
    public void EveryDiscoveredAction_IsInTheHandTypedSpecTable()
    {
        var discovered = DiscoverEndpoints();
        Assert.NotEmpty(discovered);

        var missing = discovered.Select(d => d.Action).Distinct(StringComparer.Ordinal).Except(SpecRolesByAction.Keys).ToList();
        Assert.True(missing.Count == 0,
            "Action(s) present on CatsController/VaccinesController but missing from this test's hand-typed HO-ADM-001 §12.3 spec table: " +
            string.Join(", ", missing));
    }

    [Fact]
    public void EveryDiscoveredEndpoint_HasABodyEntryIfItNeedsOne()
    {
        var discovered = DiscoverEndpoints();

        var missing = discovered.Select(d => d.Key).Distinct(StringComparer.Ordinal).Except(BodiesByRoute.Keys).ToList();
        Assert.True(missing.Count == 0,
            "Endpoint(s) discovered on CatsController/VaccinesController with no body entry in BodiesByRoute: " + string.Join(", ", missing));
    }

    public static IEnumerable<object[]> EndpointCases() =>
        DiscoverEndpoints().Select(e => new object[] { e.Key, e.Action, e.OwnerScope, e.Method, e.RouteTemplate });

    private static readonly ConcurrentDictionary<string, Lazy<Task<(Guid StaffAccountId, string Mobile, string Password)>>> StaffCache = new();

    private Task<(Guid StaffAccountId, string Mobile, string Password)> GetOrSeedStaffAsync(string role) =>
        StaffCache.GetOrAdd(role, r => new Lazy<Task<(Guid, string, string)>>(() => SeedStaffAsync(r))).Value;

    /// <summary>The full matrix, one theory case per reflection-discovered endpoint: anonymous, each
    /// of the 8 staff roles, and a customer (split into "own"/"other" for the three owner-scoped
    /// actions, or a single non-owner check for every other action). Failures across every caller
    /// type for this one endpoint are collected and reported together, rather than stopping at the
    /// first, so a single run shows the whole picture for that endpoint.</summary>
    [Theory]
    [MemberData(nameof(EndpointCases))]
    public async Task Endpoint_MatchesTheSpecTableForEveryCallerType(string label, string action, string ownerScope, string method, string routeTemplate)
    {
        Assert.True(SpecRolesByAction.TryGetValue(action, out var expectedRoles), $"No spec entry for action '{action}' ({label}).");
        Assert.True(BodiesByRoute.TryGetValue(label, out var bodyJson), $"No body entry for '{label}'.");

        var failures = new List<string>();

        var (ownerClient, ownerId, _) = await RegisterAndSignInCustomerAsync();
        var (otherClient, _, _) = await RegisterAndSignInCustomerAsync();
        var catId = await SeedCatAsync(ownerId);
        var url = "/" + routeTemplate.Replace("{catId:guid}", catId.ToString());

        // (1) Anonymous -> 401, always (ADR-036/ADR-043: no identity, nothing to audit).
        var anonymousResponse = await SendAsync(CreateClient(), method, url, bodyJson);
        if (anonymousResponse.StatusCode != HttpStatusCode.Unauthorized)
            failures.Add($"anonymous: expected 401, got {(int)anonymousResponse.StatusCode}");

        // (2) Each of the 8 staff roles.
        foreach (var role in StaffRoles.All)
        {
            var (_, mobile, password) = await GetOrSeedStaffAsync(role);
            using var staffClient = await SignInStaffAsync(mobile, password);
            var response = await SendAsync(staffClient, method, url, bodyJson);

            if (expectedRoles!.Contains(role, StringComparer.Ordinal))
            {
                if (response.StatusCode is HttpStatusCode.Unauthorized or HttpStatusCode.Forbidden)
                    failures.Add($"{role}: expected allowed (not 401/403), got {(int)response.StatusCode}");
            }
            else
            {
                if (response.StatusCode != HttpStatusCode.Forbidden)
                    failures.Add($"{role}: expected 403, got {(int)response.StatusCode}");
            }
        }

        // (3) Customer.
        if (SpecCustomerOwnActions.Contains(action))
        {
            var ownResponse = await SendAsync(ownerClient, method, url, bodyJson);
            if (ownResponse.StatusCode is HttpStatusCode.Unauthorized or HttpStatusCode.Forbidden or HttpStatusCode.NotFound)
                failures.Add($"customer (own): expected allowed, got {(int)ownResponse.StatusCode}");

            if (ownerScope == nameof(OwnerScope.Cat))
            {
                var otherResponse = await SendAsync(otherClient, method, url, bodyJson);
                if (otherResponse.StatusCode != HttpStatusCode.NotFound)
                    failures.Add($"customer (other's cat): expected 404, got {(int)otherResponse.StatusCode}");
            }
        }
        else
        {
            var customerResponse = await SendAsync(ownerClient, method, url, bodyJson);
            if (customerResponse.StatusCode != HttpStatusCode.Forbidden)
                failures.Add($"customer (not an owner-scoped action): expected 403, got {(int)customerResponse.StatusCode}");
        }

        Assert.True(failures.Count == 0, $"{label} ({action}, OwnerScope.{ownerScope}):\n  " + string.Join("\n  ", failures));
    }

    private static async Task<HttpResponseMessage> SendAsync(HttpClient client, string method, string url, string? bodyJson)
    {
        var request = new HttpRequestMessage(new HttpMethod(method), url);
        if (bodyJson is not null) request.Content = new StringContent(bodyJson, Encoding.UTF8, "application/json");
        return await client.SendAsync(request);
    }
